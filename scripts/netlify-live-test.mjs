import { chromium } from "playwright";
const BASE = "https://presence-moneymaka.netlify.app";
const b = await chromium.launch({ headless: true });
const p = await b.newPage({ viewport: { width: 412, height: 860 } });
const sfn = [];
p.on("response", r => { if (r.url().includes("_serverFn")) sfn.push(`${r.status()} ${r.url().split("?")[0].slice(-60)}`); });
await p.goto(BASE + "/", { waitUntil: "networkidle" });
await p.locator("article").filter({ hasText: "Moneymaka" }).getByRole("link", { name: /call/i }).first().click();
await p.waitForURL(/\/call\//); await p.waitForTimeout(2500);
const hash = () => p.evaluate(() => { const c = document.querySelector("canvas"); if (!c) return null; const x = c.getContext("2d"); let h = 0; for (let i = 0; i < 20; i++) { const d = x.getImageData(Math.floor(c.width*(i+1)/22), Math.floor(c.height*0.55), 1, 1).data; h = (h*33 + d[0] + d[1]*3 + d[2]*7) >>> 0; } return h; });
const h1 = await hash(); await p.waitForTimeout(700); const h2 = await hash();
const box = p.getByPlaceholder(/type|say|message/i).or(p.locator("textarea, input[type=text]")).first();
await box.fill("What's 12 times 12, and what's your name?");
const send = p.getByRole("button", { name: /send/i }).first();
if (await send.count()) await send.click(); else await box.press("Enter");
await p.waitForTimeout(9000);
const h3 = await hash();
const text = await p.locator("body").innerText();
await p.screenshot({ path: "/workspace/presence/tmp/netlify-live.png" });
console.log(JSON.stringify({ h1, h2, h3, demo: /demo/i.test(text), sfn }, null, 1));
console.log("---BODY---\n" + text);
await b.close();
